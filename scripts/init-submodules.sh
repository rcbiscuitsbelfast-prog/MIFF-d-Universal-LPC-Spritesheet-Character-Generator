#!/bin/bash

# Initialize LPC Asset Submodules
# Run this script after cloning the repository

set -e

echo "?????????????????????????????????????????????????????????????????????????????"
echo "?           LPC Avatar Builder - Submodule Initialization                  ?"
echo "?????????????????????????????????????????????????????????????????????????????"
echo ""

# Check if git is available
if ! command -v git &> /dev/null; then
    echo "? Error: git is not installed"
    exit 1
fi

echo "?? Initializing Git submodules..."
git submodule init

echo "?? Fetching submodule content..."
git submodule update --recursive --remote

# Check if assets were downloaded
if [ -d "assets/lpc" ]; then
    echo "? LPC assets submodule initialized successfully"
    
    # Count files in submodule
    FILE_COUNT=$(find assets/lpc -type f | wc -l)
    echo "?? Found $FILE_COUNT files in LPC assets"
    
    # Create symlink to spritesheets if it doesn't exist
    if [ ! -L "spritesheets" ] && [ -d "assets/lpc/spritesheets" ]; then
        echo "?? Creating symlink: spritesheets -> assets/lpc/spritesheets"
        ln -s assets/lpc/spritesheets spritesheets
    fi
else
    echo "??  Warning: LPC assets directory not found"
    echo "   Make sure the submodule URL is correct in .gitmodules"
fi

echo ""
echo "? Submodule initialization complete!"
echo ""
echo "Next steps:"
echo "  1. npm install              # Install dependencies"
echo "  2. npm start                # Start the server"
echo "  3. Open http://localhost:3000 in your browser"
echo ""
